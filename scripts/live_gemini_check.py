"""One real Gemini call, end to end, for release verification.

Makes exactly ONE request to the Gemini API using the key in `.env`
(GEMINI_API_KEY), runs the response through the same parsing and claim
check the API uses, and saves a sanitised example report.

The key is never printed. Nothing is written to the database.

Usage:
    python scripts/live_gemini_check.py
    python scripts/live_gemini_check.py --image path/to/smear.jpg
"""

from __future__ import annotations

import argparse
import sys
from datetime import date
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from PIL import Image  # noqa: E402

from bloodcell.config import PROJECT_ROOT, get_settings  # noqa: E402
from bloodcell.inference import Detector  # noqa: E402
from bloodcell.pipeline import analyze_image  # noqa: E402

OUT = PROJECT_ROOT / "docs" / "examples" / "gemini_report_example.md"
DEFAULT_IMAGE = PROJECT_ROOT / "BCCD_Dataset" / "BCCD" / "JPEGImages" / "BloodImage_00003.jpg"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--image", type=Path, default=DEFAULT_IMAGE)
    args = parser.parse_args()

    settings = get_settings()
    if not settings.gemini_api_key:
        print("GEMINI_API_KEY is not set. Add it to .env (never commit it) and re-run.")
        return 2
    if not args.image.exists():
        print(f"Image not found: {args.image} (run `make data` or pass --image)")
        return 2

    analysis = analyze_image(Detector(settings), Image.open(args.image), args.image.name, settings, use_llm=True)
    v = analysis.report_validation
    print(f"model: {settings.gemini_model}")
    print(f"report_source: {analysis.report_source}")
    print(f"validation: {v.status} ({v.numbers_checked} numeric values checked)")
    for issue in v.issues:
        print(f"  issue: {issue}")
    print(f"counts: {analysis.counts} total={analysis.total_detections} QC={analysis.quality_control.status}")

    if analysis.report_source != "gemini":
        print("\nNo example saved: the live narrative was not accepted (template fallback was used).")
        return 1

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "# Example report from a live Gemini call\n\n"
        f"- Date: {date.today().isoformat()}\n"
        f"- LLM: `{settings.gemini_model}` (structured JSON output)\n"
        f"- Detector: `{analysis.model_name}`\n"
        f"- Input: `{analysis.filename}` (BCCD dataset, public research image)\n"
        f"- Claim check: **{v.status}**, {v.numbers_checked} numeric values checked\n"
        f"- Generated by `scripts/live_gemini_check.py`; unedited model output below.\n\n---\n\n"
        f"{analysis.ai_report}\n"
    )
    print(f"\nSaved {OUT.relative_to(PROJECT_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
